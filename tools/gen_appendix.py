PC = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}

def pc(n):
    return (PC[n[0]] + n[1:].count('#') - n[1:].count('b')) % 12

def two_octaves(names):
    """D1 から始めて2オクターブ上の D3 まで、音名に実音のオクターブを付ける。"""
    seq = names + names + ['D']
    out, prev = [], None
    for n in seq:
        m = 26 if prev is None else next(x for x in range(prev + 1, prev + 13) if x % 12 == pc(n))
        out.append(f"{n}{m // 12 - 1}/4")
        prev = m
    return out

